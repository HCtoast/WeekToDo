-- ── 이월된 TODO 슬롯이 앵커를 따라가게 ──────────────────────────────────────
--
-- 왜:
-- 어제 못 끝낸 TODO는 이월될 때 오늘 앵커에서부터 순서대로 붙는다. 그런데 그 시각이
-- **이월 시점의 앵커 값을 절대 시각으로 스냅샷해서** 저장되므로, 나중에 앵커를 옮겨도
-- 따라가지 않는다. "오늘은 두 시간 늦게 시작"이라고 앵커를 미뤄도 이월분만 옛 자리에
-- 남아, 큐는 밀렸는데 TODO는 안 밀리는 어긋난 화면이 된다.
--
-- 설계 원칙 1("파생 시각은 저장하지 않는다")이 local_events에만 적용되고
-- todo_time_slots는 "절대 좌표라 예외"로 빠져 있는데, 앵커에서 나온 슬롯은
-- 절대 좌표가 아니라 파생값이다. 성격이 다른 두 종류가 한 테이블에 섞여 있던 것이 뿌리다.
--
-- 무엇을 저장하나:
-- 시각을 오프셋으로 바꾸지는 않는다. 그러면 슬롯이 두 종류가 되어 밀림 계산·드래그·
-- 자연어 도구가 전부 분기를 타야 한다. 대신 **출처 표시**만 남기고, 앵커가 바뀌는 순간
-- 묶인 슬롯들을 다시 계산해 덮어쓴다. 국소적인 규칙이라 파급이 작다.
--
-- 기존 행은 전부 0이다 — 사용자가 직접 놓은 것으로 본다. 이월된 것을 소급해 찾을
-- 방법이 없고, 잘못 묶어서 멀쩡한 일정이 저절로 움직이는 쪽이 더 나쁘다.

ALTER TABLE todo_time_slots ADD COLUMN anchor_bound INTEGER NOT NULL DEFAULT 0
  CHECK (anchor_bound IN (0, 1));
